const { query } = require("../../config/database");

const SUPPORTED_LANGUAGES = ["hi", "gu"];
const LANGUAGE_NAMES = {
  hi: "Hindi",
  gu: "Gujarati",
};

let tableEnsured = false;

async function ensureTranslationsTable() {
  if (tableEnsured) return;

  await query(`
    CREATE TABLE IF NOT EXISTS content_translations (
      id INT AUTO_INCREMENT PRIMARY KEY,
      entity_type VARCHAR(100) NOT NULL,
      entity_id INT NOT NULL,
      field_name VARCHAR(100) NOT NULL,
      language_code ENUM('hi', 'gu') NOT NULL,
      translated_value LONGTEXT NULL,
      auto_generated TINYINT(1) NOT NULL DEFAULT 0,
      created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
      updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
      UNIQUE KEY unique_content_translation (entity_type, entity_id, field_name, language_code),
      INDEX idx_content_translation_entity (entity_type, entity_id),
      INDEX idx_content_translation_language (language_code)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
  `);

  tableEnsured = true;
}

function normalizeLanguage(languageCode) {
  return SUPPORTED_LANGUAGES.includes(languageCode) ? languageCode : "en";
}

function normalizeTranslations(translations = {}) {
  return SUPPORTED_LANGUAGES.reduce((acc, lang) => {
    acc[lang] = translations?.[lang] && typeof translations[lang] === "object" ? translations[lang] : {};
    return acc;
  }, {});
}

async function translateWithLibreTranslate(text, targetLanguage) {
  const endpoint = process.env.TRANSLATION_API_URL;
  if (!endpoint) return null;

  const response = await fetch(endpoint, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      q: text,
      source: "en",
      target: targetLanguage,
      format: "text",
      api_key: process.env.TRANSLATION_API_KEY || undefined,
    }),
  });

  const raw = await response.text();
  let data = {};
  try {
    data = raw ? JSON.parse(raw) : {};
  } catch (_) {}

  if (!response.ok) {
    throw new Error(data?.error || data?.message || raw || `LibreTranslate failed with ${response.status}`);
  }

  return data?.translatedText || "";
}

async function translateWithMyMemory(text, targetLanguage) {
  const url = new URL("https://api.mymemory.translated.net/get");
  url.searchParams.set("q", text);
  url.searchParams.set("langpair", `en|${targetLanguage}`);

  const response = await fetch(url.toString(), {
    method: "GET",
    headers: {
      Accept: "application/json",
      "User-Agent": "VishwAnjanadhamAdmin/1.0",
    },
  });

  const raw = await response.text();
  let data = {};
  try {
    data = raw ? JSON.parse(raw) : {};
  } catch (_) {}

  if (!response.ok) {
    throw new Error(data?.responseDetails || raw || `MyMemory failed with ${response.status}`);
  }

  if (data?.responseStatus && Number(data.responseStatus) >= 400) {
    throw new Error(data?.responseDetails || `MyMemory failed with ${data.responseStatus}`);
  }

  return data?.responseData?.translatedText || "";
}

async function translateText(text, targetLanguage) {
  const source = typeof text === "string" ? text.trim() : "";
  if (!source) return "";

  if (process.env.TRANSLATION_API_URL) {
    return translateWithLibreTranslate(source, targetLanguage);
  }

  return translateWithMyMemory(source, targetLanguage);
}
async function autoFillTranslations(fields = {}, targetLanguages = SUPPORTED_LANGUAGES) {
  const languages = targetLanguages.filter((lang) => SUPPORTED_LANGUAGES.includes(lang));
  const result = languages.reduce((acc, lang) => ({ ...acc, [lang]: {} }), {});
  const errors = [];

  for (const [fieldName, value] of Object.entries(fields)) {
    const source = typeof value === "string" ? value.trim() : "";
    for (const lang of languages) {
      if (!source) {
        result[lang][fieldName] = "";
        continue;
      }

      try {
        result[lang][fieldName] = await translateText(source, lang);
      } catch (error) {
        result[lang][fieldName] = "";
        errors.push({ field_name: fieldName, language_code: lang, message: error.message });
      }
    }
  }

  return { translations: result, errors };
}

async function saveEntityTranslations(entityType, entityId, translations = {}, { autoGenerated = false } = {}) {
  await ensureTranslationsTable();
  const normalized = normalizeTranslations(translations);

  for (const lang of SUPPORTED_LANGUAGES) {
    for (const [fieldName, rawValue] of Object.entries(normalized[lang])) {
      const value = rawValue === undefined || rawValue === null ? "" : String(rawValue);
      await query(
        `INSERT INTO content_translations
         (entity_type, entity_id, field_name, language_code, translated_value, auto_generated)
         VALUES (?, ?, ?, ?, ?, ?)
         ON DUPLICATE KEY UPDATE translated_value = VALUES(translated_value), auto_generated = VALUES(auto_generated)`,
        [entityType, entityId, fieldName, lang, value, autoGenerated ? 1 : 0]
      );
    }
  }
}

async function getEntityTranslations(entityType, entityId) {
  await ensureTranslationsTable();
  const rows = await query(
    `SELECT field_name, language_code, translated_value, auto_generated
     FROM content_translations
     WHERE entity_type = ? AND entity_id = ?`,
    [entityType, entityId]
  );

  const translations = { hi: {}, gu: {}, _meta: { hi: {}, gu: {} } };
  for (const row of rows) {
    translations[row.language_code][row.field_name] = row.translated_value || "";
    translations._meta[row.language_code][row.field_name] = {
      auto_generated: Boolean(row.auto_generated),
    };
  }

  return translations;
}

async function deleteEntityTranslations(entityType, entityId) {
  await ensureTranslationsTable();
  await query("DELETE FROM content_translations WHERE entity_type = ? AND entity_id = ?", [entityType, entityId]);
}

async function overlayEntityTranslations(entityType, entityOrItems, languageCode, fields = []) {
  const lang = normalizeLanguage(languageCode);
  if (lang === "en") return entityOrItems;

  const isArray = Array.isArray(entityOrItems);
  const items = isArray ? entityOrItems : [entityOrItems].filter(Boolean);
  if (!items.length) return entityOrItems;

  await ensureTranslationsTable();
  const ids = items.map((item) => Number(item.id)).filter(Boolean);
  if (!ids.length) return entityOrItems;

  const placeholders = ids.map(() => "?").join(",");
  const rows = await query(
    `SELECT entity_id, field_name, translated_value
     FROM content_translations
     WHERE entity_type = ? AND language_code = ? AND entity_id IN (${placeholders})`,
    [entityType, lang, ...ids]
  );

  const byEntity = rows.reduce((acc, row) => {
    acc[row.entity_id] = acc[row.entity_id] || {};
    acc[row.entity_id][row.field_name] = row.translated_value;
    return acc;
  }, {});

  const translatedItems = items.map((item) => {
    const translated = byEntity[item.id] || {};
    const next = { ...item, _language: lang };
    for (const field of fields) {
      if (translated[field]) {
        next[field] = translated[field];
      }
    }
    return next;
  });

  return isArray ? translatedItems : translatedItems[0];
}

module.exports = {
  SUPPORTED_LANGUAGES,
  autoFillTranslations,
  saveEntityTranslations,
  getEntityTranslations,
  deleteEntityTranslations,
  overlayEntityTranslations,
};

